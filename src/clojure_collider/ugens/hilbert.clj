(ns clojure-collider.ugens.hilbert
  "Port of cl-collider ugens/Hilbert.lisp (mechanical defugen forms).
  Generated by scripts/emit_ugens.clj; customs hand-ported separately."
  (:require [clojure-collider.synth.ugen :as ugen]
            [clojure-collider.synth.operators :as op]
            [clojure-collider.ugens.delays :as delays]
            [clojure-collider.ugens.fft :as fft]))

(def ^:private no-check (fn [_] nil))

(defn hilbert:ar
  "Port of Hilbert.lisp (hilbert \"Hilbert\")."
  ([in] (hilbert:ar in 1.0 0.0))
  ([in mul] (hilbert:ar in mul 0.0))
  ([in mul add]
   (op/madd (ugen/multinew (fn [_cls in] (ugen/multiout-new "Hilbert" :audio :bipolar 2 in))
                           'multiout-ugen in)
            mul add)))

(defn freq-shift:ar
  "Port of Hilbert.lisp (freq-shift \"FreqShift\")."
  ([in] (freq-shift:ar in 0.0 0.0 1.0 0))
  ([in freq] (freq-shift:ar in freq 0.0 1.0 0))
  ([in freq phase] (freq-shift:ar in freq phase 1.0 0))
  ([in freq phase mul] (freq-shift:ar in freq phase mul 0))
  ([in freq phase mul add]
   (op/madd (ugen/multinew (fn [cls in freq phase] (ugen/ugen-new "FreqShift" :audio cls no-check :bipolar in freq phase))
                           'ugen in freq phase)
            mul add)))


;; ---- hand customs (preserved across regeneration) ----

(defn hilbert-fir:ar
  "Port of Hilbert.lisp hilbert-fir.ar: 90-degree FIR Hilbert pair. The FFT
  chain (FFT with default hop/wintype/active/winsize through PV_PhaseShift90)
  feeds IFFT while the input takes a BufDur-compensated DelayN branch.
  Returns [delayed shifted]."
  [in buffer]
  (let [chain (ugen/multinew (fn [cls & inputs] (apply ugen/ugen-new "FFT" :control cls identity :bipolar inputs))
                             'pv-chain-ugen buffer in 0.5 0 1 0)
        chain (ugen/multinew (fn [cls c] (ugen/ugen-new "PV_PhaseShift90" :control cls identity :bipolar c))
                             'pv-chain-ugen chain)
        delay (ugen/multinew (fn [cls buf] (ugen/ugen-new "BufDur" :control cls no-check :bipolar buf))
                             'ugen buffer)]
    [(delays/delay-n:ar in delay delay)
     (fft/ifft:ar chain)]))
