(defn- smooth-fold-s-gen [rate in lo hi fold-range smooth-amount delta]
  (let [fold (if (= rate :control) trig/fold:kr trig/fold:ar)
        select (if (= rate :control) osc/select:kr osc/select:ar)
        clip (if (= rate :control) smooth-clip-s:kr smooth-clip-s:ar)
        case-var (op/+ (op/< in lo) (op/* (op/> in hi) 2.0))
        fold-range-abs (op/* (op/- hi lo) fold-range)
        thr-1 (op/+ lo fold-range-abs)
        thr-2 (op/- hi fold-range-abs)]
    (select case-var
            [(clip in lo hi smooth-amount delta)
             (clip (fold in lo thr-1) lo thr-1 smooth-amount delta)
             (clip (fold in thr-2 hi) thr-2 hi smooth-amount delta)])))

