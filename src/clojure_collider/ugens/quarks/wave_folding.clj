(defn- smooth-clip-s-gen [rate in lo hi amount delta]
  (let [dc (if (= rate :control) line/dc:kr line/dc:ar)
        select (if (= rate :control) osc/select:kr osc/select:ar)
        sum (op/+ hi lo)
        dif (op/* (op/max (op/abs (op/- hi lo)) delta)
                  (op/- (op/* (op/>= (op/- hi lo) (dc 0)) 2) 1))
        from-factor (op// 2 dif)
        from-offset (op/+ (op/* from-factor (op/neg hi)) 1)
        in (op/+ (op/* from-factor in) from-offset)
        x0 (op/min (op/- 1.0 amount) (op/- 1.0 delta))
        w (op/* x0 Math/PI 0.5)
        p (op// 1.0 (op/+ (op/- 1.0 (op/sin w)) (op/* w (op/cos w))))
        slope (op/* p Math/PI 0.5 (op/cos w))
        lin-sig (op/* slope in)
        sine-sig (op/* (op/+ (op/* (op/- (op/sin (op/* (op/abs in) Math/PI 0.5)) 1.0) p) 1.0)
                       (op/sign in))
        case-var (op/+ (op/> (op/abs in) x0) (op/>= (op/abs in) 1) (op/<= in -1))]
    (select case-var
            (op/* (op/+ (op/* [lin-sig sine-sig (dc 1.0) (dc -1.0)] dif) sum)
                  0.5))))

(defn smooth-clip-s:ar
  "Port of WaveFolding.lisp smooth-clip-s.ar."
  ([in] (smooth-clip-s:ar in -1.0 1.0 0.5 0.00001))
  ([in lo] (smooth-clip-s:ar in lo 1.0 0.5 0.00001))
  ([in lo hi] (smooth-clip-s:ar in lo hi 0.5 0.00001))
  ([in lo hi amount] (smooth-clip-s:ar in lo hi amount 0.00001))
  ([in lo hi amount delta]
   (ugen/multinew (fn [_ in lo hi amount delta] (smooth-clip-s-gen :audio in lo hi amount delta))
                  'ugen in lo hi amount delta)))

