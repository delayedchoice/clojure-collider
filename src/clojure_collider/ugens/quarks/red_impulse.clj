(defn red-impulse:ar
  "Port of quarks/redSys/RedImpulse.lisp (red-impulse \"RedImpulse\")."
  ([] (red-impulse:ar 440.0 0.0 1.0 0.0))
  ([freq] (red-impulse:ar freq 0.0 1.0 0.0))
  ([freq reset] (red-impulse:ar freq reset 1.0 0.0))
  ([freq reset mul] (red-impulse:ar freq reset mul 0.0))
  ([freq reset mul add]
   (let [osc (trig/phasor:ar reset (op// freq (info/sample-rate:ir)))
         sig (op/+ (op/< (op/- osc (delays/delay-1:ar osc)) 0) (osc/impulse:ar 0))]
     (op/mul-add sig mul add))))

