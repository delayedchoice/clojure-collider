(defn f-sin-osc:ar
  "Port of FSinOsc.lisp (f-sin-osc \"FSinOsc\")."
  ([] (f-sin-osc:ar 440.0 0.0 1.0 0.0))
  ([freq] (f-sin-osc:ar freq 0.0 1.0 0.0))
  ([freq iphase] (f-sin-osc:ar freq iphase 1.0 0.0))
  ([freq iphase mul] (f-sin-osc:ar freq iphase mul 0.0))
  ([freq iphase mul add]
   (op/madd (ugen/multinew (fn [cls freq iphase] (ugen/ugen-new "FSinOsc" :audio cls no-check :bipolar freq iphase))
                           'ugen freq iphase)
            mul add)))

