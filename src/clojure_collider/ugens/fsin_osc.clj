;; ---- hand customs (preserved across regeneration) ----

(defrecord SpecArray [values])


(defn- flop-arg
  "Port of FSinOsc.lisp flop-argument: nil row -> default singleton,
   else op/flop (multichannel transpose)."
  [lst default]
  (op/flop (if (nil? lst) [default] (if (sequential? lst) (vec lst) [lst]))))

(defn- spec-combos
  "Pad parallel [freqs amps phases/decays] spec lists to 3, flop each and
   transpose via multinew-list into per-partial triple groups. Mirrors the
   lst-operation/mapcar-make-array body of klang/klank: one group per
   multichannel combo (usually exactly one)."
  [sc-name specs defaults]
  (let [specs (vec specs)
        padded (vec (concat specs (repeat (- 3 (count specs)) nil)))]
    (when (nil? (first padded))
      (throw (ex-info (str sc-name " requires a freqs spec list") {:specs specs})))
    (ugen/multinew-list (fn [_ & args] (vec args)) nil
                        (mapv flop-arg (take 3 padded) defaults))))

(defn klang:ar
  "Port of FSinOsc.lisp (klang \"Klang\"). specifications-array-ref is 3
   parallel per-partial lists [freqs amps phases] (amps/phases may be nil
   for 1.0/0.0 defaults). One multiout unit per spec combo, one channel
   per partial (flattened interleaved triples, like upstream new1)."
  ([specifications-array-ref] (klang:ar specifications-array-ref 1.0 0.0))
  ([specifications-array-ref freq-scale] (klang:ar specifications-array-ref freq-scale 0.0))
  ([specifications-array-ref freq-scale freq-offset]
   (ugen/unbubble
    (ugen/multinew-list
     (fn [_ fs fo arr]
       (let [triples (:values arr)]
         (apply ugen/multiout-new "Klang" :audio :bipolar (count triples)
                fs fo (vec (mapcat identity triples)))))
     nil
     [freq-scale freq-offset
      (mapv ->SpecArray (spec-combos "Klang" specifications-array-ref [nil 1.0 0.0]))]))))

(defn klank:ar
  "Port of FSinOsc.lisp (klank \"Klank\"). specifications-array-ref is 3
   parallel per-partial lists [freqs amps decay-times] (amps/decay-times
   may be nil for 1.0 defaults). One multiout unit per spec combo, one
   channel per partial (flattened interleaved triples, like upstream new1)."
  ([specifications-array-ref input] (klank:ar specifications-array-ref input 1.0 0.0 1.0))
  ([specifications-array-ref input freq-scale] (klank:ar specifications-array-ref input freq-scale 0.0 1.0))
  ([specifications-array-ref input freq-scale freq-offset] (klank:ar specifications-array-ref input freq-scale freq-offset 1.0))
  ([specifications-array-ref input freq-scale freq-offset decay-scale]
   (ugen/unbubble
    (ugen/multinew-list
     (fn [_ in fs fo ds arr]
       (let [triples (:values arr)]
         (apply ugen/multiout-new "Klank" :audio :bipolar (count triples)
                in fs fo ds (vec (mapcat identity triples)))))
     nil
     [input freq-scale freq-offset decay-scale
      (mapv ->SpecArray (spec-combos "Klank" specifications-array-ref [nil 1.0 1.0]))]))))

(defn- sin-osc-unit
  "Bare SinOsc (freq phase) for dyn-klang expansion; mirrors osc/sin-osc."
  [rate freq phase]
  (ugen/multinew (fn [cls f p] (ugen/ugen-new "SinOsc" rate cls no-check :bipolar f p))
                 'pure-ugen freq phase))

(defn- ringz-unit
  "Bare Ringz (in freq decay) for dyn-klank expansion; mirrors filter/ringz."
  [rate in freq decay]
  (ugen/multinew (fn [cls i f d] (ugen/ugen-new "Ringz" rate cls ugen/check-same-rate-as-first-input :bipolar i f d))
                 'pure-ugen in freq decay))

(defn dyn-klang:ar
  "Port of FSinOsc.lisp (dyn-klang \"DynKlang\"). Client-side expansion
   into summed SinOsc units (upstream new1 builds no DynKlang node).
   array-ref is 3 parallel lists [freqs amps phases]; entries may be
   ugens re-read each block."
  ([array-ref] (dyn-klang:ar array-ref 1.0 0.0))
  ([array-ref freq-scale] (dyn-klang:ar array-ref freq-scale 0.0))
  ([array-ref freq-scale freq-offset]
   (ugen/unbubble
    (ugen/multinew-list
     (fn [_ arr fs fo]
       (let [rows (:values arr)
             r0 (nth rows 0 nil)
             r1 (nth rows 1 nil)
             r2 (nth rows 2 nil)
             freqs (if (nil? r0) (op/+ (op/* [440.0] fs) fo) r0)
             amps (if (nil? r1) [1.0] r1)
             phases (if (nil? r2) [0.0] r2)]
         (op/sum (op/madd (sin-osc-unit :audio freqs phases) amps 0.0))))
     nil
     [(->SpecArray (vec array-ref)) freq-scale freq-offset]))))

