(ns clojure-collider.ugens.moog-ff
  "Port of cl-collider ugens/MoogFF.lisp (mechanical defugen forms).
  Generated by scripts/emit_ugens.clj; customs hand-ported separately."
  (:require [clojure-collider.synth.ugen :as ugen]
            [clojure-collider.synth.operators :as op]))

(defn moog-ff:ar
  "Port of MoogFF.lisp (moog-ff \"MoogFF\")."
  ([in] (moog-ff:ar in 100 2 0 1 0))
  ([in freq] (moog-ff:ar in freq 2 0 1 0))
  ([in freq gain] (moog-ff:ar in freq gain 0 1 0))
  ([in freq gain reset] (moog-ff:ar in freq gain reset 1 0))
  ([in freq gain reset mul] (moog-ff:ar in freq gain reset mul 0))
  ([in freq gain reset mul add]
   (op/madd (ugen/multinew (fn [cls in freq gain reset] (ugen/ugen-new "MoogFF" :audio cls ugen/check-same-rate-as-first-input :bipolar in freq gain reset))
                           'pure-ugen in freq gain reset)
            mul add)))

