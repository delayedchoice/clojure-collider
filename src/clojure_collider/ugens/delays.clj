(def ^:private no-check (fn [_] nil))

(defn as-audio-rate-input
  "Port of Delays.lisp as-audio-rate-input: audio input passes through,
   anything else is lifted through K2A (per-channel via multinew)."
  [input]
  (ugen/unbubble
   (ugen/multinew (fn [_cls in]
                    (if (= :audio (ugen/rate in)) in (line/k2a:ar in)))
                  'ugen input)))

(defn delay-1:ar
  "Port of Delays.lisp (Delay-1 \"Delay1\")."
  ([] (delay-1:ar 0.0 1.0 0.0 nil))
  ([in] (delay-1:ar in 1.0 0.0 nil))
  ([in mul] (delay-1:ar in mul 0.0 nil))
  ([in mul add] (delay-1:ar in mul add nil))
  ([in mul add x1]
   (op/madd (ugen/multinew (fn [cls in iexpr1] (ugen/ugen-new "Delay1" :audio cls no-check :bipolar in iexpr1))
                           'pure-ugen in (if x1 x1 0.0))
            mul add)))

