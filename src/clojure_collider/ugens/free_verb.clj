(ns clojure-collider.ugens.free-verb
  "Port of cl-collider ugens/FreeVerb.lisp (mechanical defugen forms).
  Generated by scripts/emit_ugens.clj; customs hand-ported separately."
  (:require [clojure-collider.synth.ugen :as ugen]
            [clojure-collider.synth.operators :as op]))

(def ^:private no-check (fn [_] nil))

(defn freeverb:ar
  "Port of FreeVerb.lisp (freeverb \"FreeVerb\")."
  ([in & {:keys [mix room damp mul add] :or {mix 0.33 room 0.5 damp 0.5 mul 1.0 add 0.0}}]
   (op/madd (ugen/multinew (fn [cls in mix room damp] (ugen/ugen-new "FreeVerb" :audio cls no-check :bipolar in mix room damp))
                           'pure-ugen in mix room damp)
            mul add)))

(defn freeverb2:ar
  "Port of FreeVerb.lisp (freeverb2 \"FreeVerb2\")."
  ([in1 in2 & {:keys [mix room damp mul add] :or {mix 0.33 room 0.5 damp 0.5 mul 1.0 add 0.0}}]
   (op/madd (ugen/multinew (fn [_cls in1 in2 mix room damp] (ugen/multiout-new "FreeVerb2" :audio :bipolar 2 in1 in2 mix room damp))
                           'multiout-ugen in1 in2 mix room damp)
            mul add)))
