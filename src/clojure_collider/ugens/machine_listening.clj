(defn onsets:kr
  "Port of MachineListening.lisp (onsets \"Onsets\"). odf-type accepts a
   keyword (:power :magsum :complex :rcomplex :phase :wphase :mkl) or its
   integer index (upstream position over odf-types)."
  ([chain] (onsets:kr chain 0.5 :rcomplex 1 0.1 10 11 1 0))
  ([chain threshold] (onsets:kr chain threshold :rcomplex 1 0.1 10 11 1 0))
  ([chain threshold odf-type] (onsets:kr chain threshold odf-type 1 0.1 10 11 1 0))
  ([chain threshold odf-type relax-time] (onsets:kr chain threshold odf-type relax-time 0.1 10 11 1 0))
  ([chain threshold odf-type relax-time floor] (onsets:kr chain threshold odf-type relax-time floor 10 11 1 0))
  ([chain threshold odf-type relax-time floor min-gap] (onsets:kr chain threshold odf-type relax-time floor min-gap 11 1 0))
  ([chain threshold odf-type relax-time floor min-gap median-span] (onsets:kr chain threshold odf-type relax-time floor min-gap median-span 1 0))
  ([chain threshold odf-type relax-time floor min-gap median-span wh-type] (onsets:kr chain threshold odf-type relax-time floor min-gap median-span wh-type 0))
  ([chain threshold odf-type relax-time floor min-gap median-span wh-type raw-odf]
   (let [types [:power :magsum :complex :rcomplex :phase :wphase :mkl]
         odf (if (and (integer? odf-type) (>= odf-type 0) (< odf-type (count types)))
               odf-type
               (first (keep-indexed (fn [i t] (when (= t odf-type) i)) types)))]
     (ugen/multinew (fn [cls chain threshold odf-type relax-time floor min-gap median-span wh-type raw-odf]
                      (ugen/ugen-new "Onsets" :control cls no-check :bipolar
                                     chain threshold odf-type relax-time floor min-gap median-span wh-type raw-odf))
                    'ugen chain threshold odf relax-time floor min-gap median-span wh-type raw-odf))))
