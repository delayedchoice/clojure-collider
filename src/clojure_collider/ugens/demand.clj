;; ---- hand customs (preserved across regeneration) ----

(defn- ensure-vec [x] (if (sequential? x) (vec x) [x]))

(defn demand:ar
  "Port of Demand.lisp (demand \"Demand\")."
  ([trig reset demand-ugens]
   (let [d (ensure-vec demand-ugens)
         n (count d)]
     (ugen/multinew-list (fn [_cls trig reset & dus] (apply ugen/multiout-new "Demand" :audio :bipolar n trig reset dus))
                         'multiout-ugen (into [trig reset] d)))))

(defn demand:kr
  "Port of Demand.lisp (demand \"Demand\")."
  ([trig reset demand-ugens]
   (let [d (ensure-vec demand-ugens)
         n (count d)]
     (ugen/multinew-list (fn [_cls trig reset & dus] (apply ugen/multiout-new "Demand" :control :bipolar n trig reset dus))
                         'multiout-ugen (into [trig reset] d)))))

(defn demand-envgen:ar
  "Port of Demand.lisp (demand-envgen \"DemandEnvGen\")."
  ([level dur & {:keys [shape curve gate reset level-scale level-bias time-scale act] :or {shape 1 curve 0 gate 1.0 reset 1.0 level-scale 1.0 level-bias 0.0 time-scale 1.0 act :no-action}}]
   (let [audio? (or (= :audio (ugen/rate gate)) (= :audio (ugen/rate reset)))
         gate (if (and audio? (not= :audio (ugen/rate gate))) (line/k2a:ar gate) gate)
         reset (if (and audio? (not= :audio (ugen/rate reset))) (line/k2a:ar reset) reset)]
     (ugen/multinew (fn [cls level dur shape curve gate reset level-scale level-bias time-scale act] (ugen/ugen-new "DemandEnvGen" :audio cls no-check :bipolar level dur shape curve gate reset level-scale level-bias time-scale (ugen/act act)))
                    'ugen level dur shape curve gate reset level-scale level-bias time-scale act))))
