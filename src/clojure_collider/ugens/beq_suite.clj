;; ---- hand customs (preserved across regeneration) ----

(defn- b-pass-sc
  "Port of BEQSuite.lisp b-pass-sc: biquad coefs [a0 a1 a0 b1 b2] as ugen
   graphs (SampleDur inlined; sos stages use the approved filter require)."
  [low-hi freq rq]
  (let [sample-dur (ugen/multinew (fn [cls] (ugen/ugen-new "SampleDur" :scalar cls no-check :bipolar)) 'ugen)
        w0 (op/* (op/* (op/* 2 Math/PI) freq) sample-dur)
        cos-w0 (op/cos w0)
        i (if (= :low low-hi) (op/- 1 cos-w0) (op/+ 1 cos-w0))
        alpha (op/* (op/* (op/sin w0) 0.5) (op/sqrt rq))
        b0rz (op/divide 1 (op/+ 1 alpha))
        a0 (op/* i 0.5 b0rz)
        a1 (op/* (if (= :low low-hi) i (op/* -1 i)) b0rz)
        b1 (op/* cos-w0 2 b0rz)
        b2 (op/* (op/- 1 alpha) (op/* -1 b0rz))]
    [a0 a1 a0 b1 b2]))

(defn- b-pass4-new
  "Port of BEQSuite.lisp b-pass4-new: two cascaded sos.ar stages sharing
   one b-pass-sc coef set (upstream applies multinew over sos.ar twice)."
  [low-hi in freq rq]
  (let [[a0 a1 a2 b1 b2] (b-pass-sc low-hi freq rq)
        stage1 (flt/sos:ar in a0 a1 a2 b1 b2)]
    (flt/sos:ar stage1 a0 a1 a2 b1 b2)))

