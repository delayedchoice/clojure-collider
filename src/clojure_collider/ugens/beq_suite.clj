            [clojure-collider.ugens.filter :as flt]))

(def ^:private no-check (fn [_] nil))

(defn b-lowpass:ar
  "Port of BEQSuite.lisp (b-lowpass \"BLowPass\")."
  ([] (b-lowpass:ar 0.0 1200.0 1.0 1.0 0.0))
  ([in] (b-lowpass:ar in 1200.0 1.0 1.0 0.0))
  ([in freq] (b-lowpass:ar in freq 1.0 1.0 0.0))
  ([in freq rq] (b-lowpass:ar in freq rq 1.0 0.0))
  ([in freq rq mul] (b-lowpass:ar in freq rq mul 0.0))
  ([in freq rq mul add]
   (op/madd (ugen/multinew (fn [cls in freq rq] (ugen/ugen-new "BLowPass" :audio cls ugen/check-same-rate-as-first-input :bipolar in freq rq))
                           'pure-ugen in freq rq)
            mul add)))

