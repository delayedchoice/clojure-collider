(defn play-buf:ar
  "Port of BufIO.lisp (play-buf \"PlayBuf\")."
  ([chanls] (play-buf:ar chanls 0 1.0 :trig 1.0 :start-pos 0.0 :loop 0.0 :act :no-action))
  ([chanls bufnum] (play-buf:ar chanls bufnum 1.0 :trig 1.0 :start-pos 0.0 :loop 0.0 :act :no-action))
  ([chanls bufnum rate & {:keys [trig start-pos loop act] :or {trig 1.0 start-pos 0.0 loop 0.0 act :no-action}}]
   (ugen/multinew (fn [_cls chanls bufnum rate trig start-pos loop act] (ugen/multiout-new "PlayBuf" :audio :bipolar chanls bufnum rate trig start-pos loop (ugen/act act)))
                           'multiout-ugen chanls bufnum rate trig start-pos loop act)))

