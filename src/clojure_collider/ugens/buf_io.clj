;; ---- hand customs (preserved across regeneration) ----

(defn- ensure-vec [x] (if (sequential? x) (vec x) [x]))

(defn tgrains:ar
  "Port of BufIO.lisp (tgrains \"TGrains\")."
  ([chanls] (tgrains:ar chanls 0 0 1 0 0.1 0.0 0.1 4))
  ([chanls trigger] (tgrains:ar chanls trigger 0 1 0 0.1 0.0 0.1 4))
  ([chanls trigger bufnum] (tgrains:ar chanls trigger bufnum 1 0 0.1 0.0 0.1 4))
  ([chanls trigger bufnum rate] (tgrains:ar chanls trigger bufnum rate 0 0.1 0.0 0.1 4))
  ([chanls trigger bufnum rate center-pos] (tgrains:ar chanls trigger bufnum rate center-pos 0.1 0.0 0.1 4))
  ([chanls trigger bufnum rate center-pos dur] (tgrains:ar chanls trigger bufnum rate center-pos dur 0.0 0.1 4))
  ([chanls trigger bufnum rate center-pos dur pan] (tgrains:ar chanls trigger bufnum rate center-pos dur pan 0.1 4))
  ([chanls trigger bufnum rate center-pos dur pan amp] (tgrains:ar chanls trigger bufnum rate center-pos dur pan amp 4))
  ([chanls trigger bufnum rate center-pos dur pan amp interp]
   (when (< chanls 2)
     (throw (ex-info "TGrains needs at least two channels." {:chanls chanls})))
   (ugen/multinew (fn [_cls chanls trigger bufnum rate center-pos dur pan amp interp] (ugen/multiout-new "TGrains" :audio :bipolar chanls trigger bufnum rate center-pos dur pan amp interp))
                  'multiout-ugen chanls trigger bufnum rate center-pos dur pan amp interp)))

