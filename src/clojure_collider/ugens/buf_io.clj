(defn tap:ar
  "Port of BufIO.lisp tap.ar (plays bufnum with a delay-offset start-pos)."
  ([] (tap:ar 0 1 0.2))
  ([bufnum] (tap:ar bufnum 1 0.2))
  ([bufnum chanls] (tap:ar bufnum chanls 0.2))
  ([bufnum chanls delay]
   (let [n (op/* delay (op/- (ugen/multinew (fn [cls] (ugen/ugen-new "SampleRate" :scalar cls no-check :bipolar))
                                            'ugen)))]
     (play-buf:ar chanls bufnum 1 :trig 0 :start-pos n :loop 1))))
