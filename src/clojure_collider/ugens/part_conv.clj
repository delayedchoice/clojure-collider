(ns clojure-collider.ugens.part-conv
  "Port of cl-collider ugens/PartConv.lisp (mechanical defugen forms).
  Generated by scripts/emit_ugens.clj; customs hand-ported separately."
  (:require [clojure-collider.synth.ugen :as ugen]
            [clojure-collider.synth.operators :as op]))

(def ^:private no-check (fn [_] nil))

(defn part-conv:ar
  "Port of PartConv.lisp (part-conv \"PartConv\")."
  ([in fftsize irbufnum] (part-conv:ar in fftsize irbufnum 1.0 0.0))
  ([in fftsize irbufnum mul] (part-conv:ar in fftsize irbufnum mul 0.0))
  ([in fftsize irbufnum mul add]
   (op/madd (ugen/multinew (fn [cls in fftsize irbufnum] (ugen/ugen-new "PartConv" :audio cls no-check :bipolar in fftsize irbufnum))
                           'ugen in fftsize irbufnum)
            mul add)))
