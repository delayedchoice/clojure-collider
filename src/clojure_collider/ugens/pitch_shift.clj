(ns clojure-collider.ugens.pitch-shift
  "Port of cl-collider ugens/PitchShift.lisp (mechanical defugen forms).
  Generated by scripts/emit_ugens.clj; customs hand-ported separately."
  (:require [clojure-collider.synth.ugen :as ugen]
            [clojure-collider.synth.operators :as op]))

(def ^:private no-check (fn [_] nil))

(defn pitch-shift:ar
  "Port of PitchShift.lisp (pitch-shift \"PitchShift\")."
  ([] (pitch-shift:ar 0.0 0.2 1.0 0.0 0.0 :mul 1.0 :add 0.0))
  ([in] (pitch-shift:ar in 0.2 1.0 0.0 0.0 :mul 1.0 :add 0.0))
  ([in window-size] (pitch-shift:ar in window-size 1.0 0.0 0.0 :mul 1.0 :add 0.0))
  ([in window-size pitch-ratio] (pitch-shift:ar in window-size pitch-ratio 0.0 0.0 :mul 1.0 :add 0.0))
  ([in window-size pitch-ratio pitch-dispersion] (pitch-shift:ar in window-size pitch-ratio pitch-dispersion 0.0 :mul 1.0 :add 0.0))
  ([in window-size pitch-ratio pitch-dispersion time-dispersion & {:keys [mul add] :or {mul 1.0 add 0.0}}]
   (op/madd (ugen/multinew (fn [cls in window-size pitch-ratio pitch-dispersion time-dispersion] (ugen/ugen-new "PitchShift" :audio cls no-check :bipolar in window-size pitch-ratio pitch-dispersion time-dispersion))
                           'pure-ugen in window-size pitch-ratio pitch-dispersion time-dispersion)
            mul add)))
