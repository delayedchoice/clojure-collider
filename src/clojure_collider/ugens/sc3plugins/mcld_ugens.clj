  ([freq] (saw-dpw:ar freq 0.0 1.0 0.0))
  ([freq iphase] (saw-dpw:ar freq iphase 1.0 0.0))
  ([freq iphase mul] (saw-dpw:ar freq iphase mul 0.0))
