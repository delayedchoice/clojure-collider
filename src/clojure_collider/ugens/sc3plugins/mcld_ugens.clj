(defn- array-out-new [sc-name rate array]
  (let [elems (if (sequential? array) (vec array) [array])]
    (apply ugen/multinew (fn [_cls & args] (apply ugen/multiout-new sc-name rate :bipolar 2 args))
             'multiout-ugen elems)))

