(ns clojure-collider.ugens.sc3plugins.deind-ugens
  "Port of cl-collider ugens/SC3plugins/DEINDUGens.lisp (custom defugen forms).
  Hand-ported; not generated by scripts/emit_ugens.clj."
  (:require [clojure-collider.synth.ugen :as ugen]))

;; ---- hand customs (preserved across regeneration) ----

(defn- stereo-pair [in]
  (let [l (if (sequential? in) (vec in) [in])]
    (if (= 1 (count l)) [(first l) (first l)] [(nth l 0) (nth l 1)])))

(defn greyhole:ar
  "Port of SC3plugins/DEINDUGens.lisp (greyhole \"GreyholeRaw\")."
  ([in] (greyhole:ar in 2.0 0.0 1.0 0.707 0.9 0.1 2.0))
  ([in delay-time] (greyhole:ar in delay-time 0.0 1.0 0.707 0.9 0.1 2.0))
  ([in delay-time damp] (greyhole:ar in delay-time damp 1.0 0.707 0.9 0.1 2.0))
  ([in delay-time damp size] (greyhole:ar in delay-time damp size 0.707 0.9 0.1 2.0))
  ([in delay-time damp size diff] (greyhole:ar in delay-time damp size diff 0.9 0.1 2.0))
  ([in delay-time damp size diff feedback] (greyhole:ar in delay-time damp size diff feedback 0.1 2.0))
  ([in delay-time damp size diff feedback mod-depth] (greyhole:ar in delay-time damp size diff feedback mod-depth 2.0))
  ([in delay-time damp size diff feedback mod-depth mod-freq]
   (let [[in0 in1] (stereo-pair in)]
     (ugen/multinew (fn [_cls in0 in1 delay-time damp size diff feedback mod-depth mod-freq]
                      (ugen/multiout-new "GreyholeRaw" :audio :bipolar 2 in0 in1 delay-time damp size diff feedback mod-depth mod-freq))
                    'multiout-ugen in0 in1 delay-time damp size diff feedback mod-depth mod-freq))))

(defn jpverb:ar
  "Port of SC3plugins/DEINDUGens.lisp (jpverb \"JPverbRaw\")."
  ([in] (jpverb:ar in 1.0 0.0 1.0 0.707 0.1 2.0 1.0 1.0 1.0 500.0 2000.0))
  ([in time] (jpverb:ar in time 0.0 1.0 0.707 0.1 2.0 1.0 1.0 1.0 500.0 2000.0))
  ([in time damp] (jpverb:ar in time damp 1.0 0.707 0.1 2.0 1.0 1.0 1.0 500.0 2000.0))
  ([in time damp size] (jpverb:ar in time damp size 0.707 0.1 2.0 1.0 1.0 1.0 500.0 2000.0))
  ([in time damp size early-diff] (jpverb:ar in time damp size early-diff 0.1 2.0 1.0 1.0 1.0 500.0 2000.0))
  ([in time damp size early-diff mod-depth] (jpverb:ar in time damp size early-diff mod-depth 2.0 1.0 1.0 1.0 500.0 2000.0))
  ([in time damp size early-diff mod-depth mod-freq] (jpverb:ar in time damp size early-diff mod-depth mod-freq 1.0 1.0 1.0 500.0 2000.0))
  ([in time damp size early-diff mod-depth mod-freq low] (jpverb:ar in time damp size early-diff mod-depth mod-freq low 1.0 1.0 500.0 2000.0))
  ([in time damp size early-diff mod-depth mod-freq low mid] (jpverb:ar in time damp size early-diff mod-depth mod-freq low mid 1.0 500.0 2000.0))
  ([in time damp size early-diff mod-depth mod-freq low mid high] (jpverb:ar in time damp size early-diff mod-depth mod-freq low mid high 500.0 2000.0))
  ([in time damp size early-diff mod-depth mod-freq low mid high low-cut] (jpverb:ar in time damp size early-diff mod-depth mod-freq low mid high low-cut 2000.0))
  ([in time damp size early-diff mod-depth mod-freq low mid high low-cut high-cut]
   (let [[in0 in1] (stereo-pair in)]
     (ugen/multinew (fn [_cls in0 in1 damp early-diff high-cut high low-cut low mod-depth mod-freq mid size time]
                      (ugen/multiout-new "JPverbRaw" :audio :bipolar 2 in0 in1 damp early-diff high-cut high low-cut low mod-depth mod-freq mid size time))
                    'multiout-ugen in0 in1 damp early-diff high-cut high low-cut low mod-depth mod-freq mid size time))))
