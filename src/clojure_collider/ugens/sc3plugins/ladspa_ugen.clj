(ns clojure-collider.ugens.sc3plugins.ladspa-ugen
  "Port of cl-collider ugens/SC3plugins/LadspaUGen.lisp (custom defugen forms).
  Hand-ported; not generated by scripts/emit_ugens.clj."
  (:require [clojure-collider.synth.ugen :as ugen]))

;; ---- hand customs (preserved across regeneration) ----

(defn ladspa:ar
  "Port of SC3plugins/LadspaUGen.lisp (ladspa \"LADSPA\"). num-channels is
  both the channel count and the first unit input (upstream new1 consumes
  the head of the input list as channels)."
  [num-channels id & args]
  (apply ugen/multinew
         (fn [_cls nch uid & rest-args]
           (apply ugen/multiout-new "LADSPA" :audio :bipolar num-channels nch uid rest-args))
         'multiout-ugen num-channels id args))
