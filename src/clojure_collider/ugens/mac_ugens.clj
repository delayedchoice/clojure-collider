  ([keycode] (key-state:kr keycode 0 1 0.2))
  ([keycode minval] (key-state:kr keycode minval 1 0.2))
  ([keycode minval maxval] (key-state:kr keycode minval maxval 0.2))
  ([keycode minval maxval lag]
   (ugen/multinew (fn [cls keycode minval maxval lag] (ugen/ugen-new "KeyState" :control cls no-check :unipolar keycode minval maxval lag))
