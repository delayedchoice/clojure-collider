(ns clojure-collider.ugens.mac-ugens
  "Port of cl-collider ugens/MacUGens.lisp (mechanical defugen forms).
  Generated by scripts/emit_ugens.clj; customs hand-ported separately."
  (:require [clojure-collider.synth.ugen :as ugen]))

(def ^:private no-check (fn [_] nil))

(defn mouse-button:kr
  "Port of MacUGens.lisp (mouse-button \"MouseButton\")."
  ([] (mouse-button:kr 0 1 0.2))
  ([minval] (mouse-button:kr minval 1 0.2))
  ([minval maxval] (mouse-button:kr minval maxval 0.2))
  ([minval maxval lag]
   (ugen/multinew (fn [cls minval maxval lag] (ugen/ugen-new "MouseButton" :control cls no-check :unipolar minval maxval lag))
                           'ugen minval maxval lag)))

(defn key-state:kr
