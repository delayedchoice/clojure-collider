;; ---- hand customs (preserved across regeneration) ----

(defn- warp->int
  "Port of MacUGens.lisp warp case mapping."
  [warp]
  (case warp
    (:linear :lin) 0
    (:exponential :exp) 1
    warp))

(defn mouse-x:kr
  "Port of MacUGens.lisp (mouse-x \"MouseX\")."
  ([] (mouse-x:kr 0 1 :linear 0.2))
  ([minval] (mouse-x:kr minval 1 :linear 0.2))
  ([minval maxval] (mouse-x:kr minval maxval :linear 0.2))
  ([minval maxval warp] (mouse-x:kr minval maxval warp 0.2))
  ([minval maxval warp lag]
   (ugen/multinew (fn [cls mn mx w l] (ugen/ugen-new "MouseX" :control cls no-check :unipolar mn mx w l))
                  'ugen minval maxval (warp->int warp) lag)))

