(ns clojure-collider.ugens.disk-io
  "Port of cl-collider ugens/DiskIO.lisp (mechanical defugen forms).
  Generated by scripts/emit_ugens.clj; customs hand-ported separately."
  (:require [clojure-collider.synth.ugen :as ugen]))

(defn disk-in:ar
  "Port of DiskIO.lisp (disk-in \"DiskIn\")."
  ([chanls bufnum] (disk-in:ar chanls bufnum 0))
  ([chanls bufnum loop]
   (ugen/multinew (fn [_cls chanls bufnum loop] (ugen/multiout-new "DiskIn" :audio :bipolar chanls bufnum loop))
                           'multiout-ugen chanls bufnum loop)))

(defn v-disk-in:ar
  "Port of DiskIO.lisp (v-disk-in \"VDiskIn\")."
  ([chanls bufnum] (v-disk-in:ar chanls bufnum 1 0 0))
  ([chanls bufnum rate] (v-disk-in:ar chanls bufnum rate 0 0))
  ([chanls bufnum rate loop] (v-disk-in:ar chanls bufnum rate loop 0))
  ([chanls bufnum rate loop send-id]
   (ugen/multinew (fn [_cls chanls bufnum rate loop send-id] (ugen/multiout-new "VDiskIn" :audio :bipolar chanls bufnum rate loop send-id))
                           'multiout-ugen chanls bufnum rate loop send-id)))


;; ---- hand customs (preserved across regeneration) ----

(defn- disk-out-check [ugen]
  (when (= :audio (:rate ugen))
    (doseq [[i inp] (map-indexed vector (rest (:inputs ugen)))]
      (when-not (= :audio (ugen/rate inp))
        (throw (ex-info (str "input was not audio rate : " inp) {:index (inc i)}))))))

(defn disk-out:ar
  "Port of DiskIO.lisp (disk-out \"DiskOut\")."
  ([bufnum channels-array]
   (ugen/unbubble
    (ugen/multinew-list (fn [cls & args] (apply ugen/ugen-new "DiskOut" :audio cls disk-out-check :bipolar args))
                        'ugen (into [bufnum] (if (sequential? channels-array) (vec channels-array) [channels-array]))))
   0))
