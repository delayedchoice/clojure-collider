(defn fft:kr
  "Port of FFT.lisp fft (plain defun): control-rate FFT chain head.
   Upstream has no rate suffix; ours takes :kr (it is a control unit)."
  ([buffer] (fft:kr buffer 0.0 0.5 0 1 0))
  ([buffer in] (fft:kr buffer in 0.5 0 1 0))
  ([buffer in hop] (fft:kr buffer in hop 0 1 0))
  ([buffer in hop wintype] (fft:kr buffer in hop wintype 1 0))
  ([buffer in hop wintype active] (fft:kr buffer in hop wintype active 0))
  ([buffer in hop wintype active winsize]
   (ugen/multinew (fn [cls buffer in hop wintype active winsize]
                    (ugen/ugen-new "FFT" :control cls no-check :bipolar
                                   buffer in hop wintype active winsize))
                  'pv-chain-ugen buffer in hop wintype active winsize)))

(defn running-sum-rms
  "Port of FFT.lisp running-sum-rms (plain scalar math helper)."
  ([in] (running-sum-rms in 40.0))
  ([in num-samp]
   (op/sqrt (op/* (running-sum:ar (op/squared in) num-samp)
                   (op/reciprocal num-samp)))))
