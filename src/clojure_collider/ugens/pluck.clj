(ns clojure-collider.ugens.pluck
  "Port of cl-collider ugens/Pluck.lisp (mechanical defugen forms).
  Generated by scripts/emit_ugens.clj; customs hand-ported separately."
  (:require [clojure-collider.synth.ugen :as ugen]
            [clojure-collider.synth.operators :as op]))

(def ^:private no-check (fn [_] nil))

(defn pluck:ar
  "Port of Pluck.lisp (pluck \"Pluck\")."
  ([] (pluck:ar 0.0 1.0 0.2 0.2 1.0 0.5 :mul 1 :add 0))
  ([in] (pluck:ar in 1.0 0.2 0.2 1.0 0.5 :mul 1 :add 0))
  ([in trig] (pluck:ar in trig 0.2 0.2 1.0 0.5 :mul 1 :add 0))
  ([in trig max-deltime] (pluck:ar in trig max-deltime 0.2 1.0 0.5 :mul 1 :add 0))
  ([in trig max-deltime deltime] (pluck:ar in trig max-deltime deltime 1.0 0.5 :mul 1 :add 0))
  ([in trig max-deltime deltime decaytime] (pluck:ar in trig max-deltime deltime decaytime 0.5 :mul 1 :add 0))
  ([in trig max-deltime deltime decaytime coef & {:keys [mul add] :or {mul 1 add 0}}]
   (op/madd (ugen/multinew (fn [cls in trig max-deltime deltime decaytime coef] (ugen/ugen-new "Pluck" :audio cls no-check :bipolar in trig max-deltime deltime decaytime coef))
                           'ugen in trig max-deltime deltime decaytime coef)
            mul add)))
