(ns clojure-collider.ugens.psin-grain
  "Port of cl-collider ugens/PSinGrain.lisp (mechanical defugen forms).
  Generated by scripts/emit_ugens.clj; customs hand-ported separately."
  (:require [clojure-collider.synth.ugen :as ugen]))

(def ^:private no-check (fn [_] nil))

(defn p-sin-grain:ar
  "Port of PSinGrain.lisp (p-sin-grain \"PSinGrain\")."
  ([] (p-sin-grain:ar 440.0 0.2 0.1))
  ([freq] (p-sin-grain:ar freq 0.2 0.1))
  ([freq dur] (p-sin-grain:ar freq dur 0.1))
  ([freq dur amp]
   (ugen/multinew (fn [cls freq dur amp] (ugen/ugen-new "PSinGrain" :audio cls no-check :bipolar freq dur amp))
                           'ugen freq dur amp)))
