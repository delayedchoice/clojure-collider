  (let [amps (cond (nil? amplitudes) [] (sequential? amplitudes) amplitudes :else [amplitudes])]
    (apply ugen/multinew (fn [cls & args] (apply ugen/ugen-new "HarmonicOsc" rate cls no-check :bipolar args))
             'ugen freq firstharmonic amps)))

