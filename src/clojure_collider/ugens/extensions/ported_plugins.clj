(defn- chen-check [ugen]
  (doseq [input (:inputs ugen)]
    (when-not (contains? #{:scalar :control} (ugen/rate input))
      (throw (ex-info "input rate should be scalar or control" {:input input})))))

(defn- chen-new [rate speed a b c]
  (let [inputs [speed a b c]]
    (chen-check {:inputs inputs})
    (apply ugen/multinew (fn [_cls & args] (apply ugen/multiout-new "Chen" rate :bipolar 3 args))
             'multiout-ugen inputs)))

