(defn- lpg-check [ugen]
  (let [[in control & rest-inputs] (:inputs ugen)]
    (when-not (and (= :audio (ugen/rate in))
                   (contains? #{:control :audio} (ugen/rate control))
                   (every? #(contains? #{:control :scalar} (ugen/rate %)) rest-inputs))
      (throw (ex-info "LPG rate requirements violated" {:inputs (:inputs ugen)})))))

(defn lpg:ar
  "Port of Extensions/PortedPlugins.lisp (lpg \"LPG\")."
  ([input controlinput & {:keys [controloffset controlscale vca resonance lowpassmode linearity]
                           :or {controloffset 0 controlscale 1 vca 1 resonance 1.5 lowpassmode 1 linearity 1}}]
   (ugen/multinew (fn [cls input controlinput controloffset controlscale vca resonance lowpassmode linearity]
                     (ugen/ugen-new "LPG" :audio cls lpg-check :bipolar input controlinput controloffset controlscale vca resonance lowpassmode linearity))
                  'ugen input controlinput controloffset controlscale vca resonance lowpassmode linearity)))

(defn- rongs-check [ugen]
  (let [[trigger sustain f0 structure brightness damping accent stretch position loss mode-num cos-freq] (:inputs ugen)]
    (when-not (and (= :scalar (ugen/rate mode-num))
                   (= :scalar (ugen/rate cos-freq))
                   (contains? #{:control :scalar :audio} (ugen/rate trigger))
                   (every? #(contains? #{:control :scalar} (ugen/rate %))
                           [sustain f0 structure brightness damping accent stretch position loss]))
      (throw (ex-info "Rongs rate requirements violated" {:inputs (:inputs ugen)})))))

(defn rongs:ar
  "Port of Extensions/PortedPlugins.lisp (rongs \"Rongs\")."
  [& {:keys [trigger sustain f0 structure brightness damping accent stretch position loss mode-num cos-freq]
       :or {trigger 0 sustain 1 f0 0.01 structure 0.5 brightness 0.5 damping 0.75 accent 0.9 stretch 0.5 position 0.15 loss 0.15 mode-num 2 cos-freq 0.25}}]
  (ugen/multinew (fn [cls trigger sustain f0 structure brightness damping accent stretch position loss mode-num cos-freq]
                    (ugen/ugen-new "Rongs" :audio cls rongs-check :bipolar trigger sustain f0 structure brightness damping accent stretch position loss mode-num cos-freq))
                 'ugen trigger sustain f0 structure brightness damping accent stretch position loss mode-num cos-freq))
