(ns clojure-collider.ugens.extensions.dyn-gen
  "Port of cl-collider ugens/Extensions/DynGen.lisp (custom DynGen forms).
  Hand-ported; not generated by scripts/emit_ugens.clj."
  (:require [clojure-collider.synth.ugen :as ugen]
            [clojure-collider.ugens.line :as line]))

;; ---- hand customs (preserved across regeneration) ----

(defonce ^:private dyn-gen-register-table (atom {}))

(defn- dyn-gen-base-hash [name]
  (let [h (hash name)]
    (* (mod h 1048576) (Integer/signum (long h)))))

(defn- dyn-gen-hash [name]
  (let [h (dyn-gen-base-hash name)]
    (doseq [n (remove #(= % name) (keys @dyn-gen-register-table))]
      (when (= h (dyn-gen-base-hash n))
        (throw (ex-info (str "Conflict hash key " name " and " n)
                        {:name name :other n}))))
    h))

(defn dyn-gen-all
  "Return all registered dyn-gen names and their params."
  []
  (mapv (fn [[k v]] [:name k :params v]) @dyn-gen-register-table))

(defn- dyn-gen-param-index [spec key owner]
  (let [ks (if (keyword? key) (clojure.core/name key) (str key))
        names (mapv str spec)
        i (.indexOf names (str "_" ks))]
    (if (>= i 0)
      i
      (let [j (.indexOf names ks)]
        (assert (>= j 0) (str "Can't found param " key " in dyn-gen module " owner))
        j))))

(defn dyn-gen:ar
  "Port of Extensions/DynGen.lisp dyn-gen.ar (\"DynGen\" multiout).
  The script must be registered under name (upstream dyn-gen-send);
  server delivery (dyn-gen-send/load/free) has no *s*/OSC counterpart
  in this port and is omitted."
  [num-output name & {:keys [inputs params update sync pause]
                      :or {inputs nil params nil update 1.0 sync 0.0 pause 0.0}}]
  (let [spec (get @dyn-gen-register-table name)]
    (assert spec (str "Can't found dyn-gen module " name))
    (let [in-list (cond (nil? inputs) [] (sequential? inputs) (vec inputs) :else [inputs])
          param-list (cond (nil? params) [] (sequential? params) (vec params) :else [params])]
      (assert (even? (count param-list)) "params should be pair of key, value")
      (let [resolved (vec (mapcat (fn [[key value]]
                                    [(dyn-gen-param-index spec key name)
                                     (if (= :audio (ugen/rate value))
                                       value
                                       (line/k2a:ar value))])
                                  (partition 2 param-list)))
            ups (mapv (fn [sig]
                        (if (= :audio (ugen/rate sig)) sig (line/k2a:ar sig)))
                      in-list)
            all (into [(dyn-gen-hash name) update sync pause
                       (count ups) (/ (count resolved) 2)]
                      (concat ups resolved))]
        (apply ugen/multinew
               (fn [_cls & args]
                 (apply ugen/multiout-new "DynGen" :audio :bipolar num-output args))
               'multiout-ugen
               all)))))
