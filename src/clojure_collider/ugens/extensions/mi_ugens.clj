(defn- mi-verb-check [ugen]
  (let [inputs (:inputs ugen)]
    (dotimes [i (- (count inputs) 6)]
      (let [in (nth inputs (+ i 6))]
        (when-not (= :audio (ugen/rate in))
          (throw (ex-info (str "input is not audio rate: " in) {:input in})))))))

