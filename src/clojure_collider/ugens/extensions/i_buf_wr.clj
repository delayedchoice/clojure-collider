(ns clojure-collider.ugens.extensions.i-buf-wr
  "Port of cl-collider ugens/Extensions/IBufWr.lisp (custom defugen forms).
  Hand-ported; not generated by scripts/emit_ugens.clj."
  (:require [clojure-collider.synth.ugen :as ugen]))

;; ---- hand customs (preserved across regeneration) ----

(defn- ibuf-wr-new [rate input-array bufnum phase interp feedback]
  (let [inputs (into [bufnum phase interp feedback]
                     (cond (nil? input-array) [] (sequential? input-array) input-array :else [input-array]))]
    (ugen/multinew-list (fn [cls & args]
                          (apply ugen/ugen-new "IBufWr" rate cls ugen/check-when-audio :bipolar args))
                        'ugen inputs)))

(defn ibuf-wr:ar
  "Port of Extensions/IBufWr.lisp (ibuf-wr \"IBufWr\")."
  ([input-array] (ibuf-wr:ar input-array 0 0.0 1 0))
  ([input-array bufnum] (ibuf-wr:ar input-array bufnum 0.0 1 0))
  ([input-array bufnum phase] (ibuf-wr:ar input-array bufnum phase 1 0))
  ([input-array bufnum phase interp] (ibuf-wr:ar input-array bufnum phase interp 0))
  ([input-array bufnum phase interp feedback]
   (ibuf-wr-new :audio input-array bufnum phase interp feedback)))

(defn ibuf-wr:kr
  "Port of Extensions/IBufWr.lisp (ibuf-wr \"IBufWr\")."
  ([input-array] (ibuf-wr:kr input-array 0 0.0 1 0))
  ([input-array bufnum] (ibuf-wr:kr input-array bufnum 0.0 1 0))
  ([input-array bufnum phase] (ibuf-wr:kr input-array bufnum phase 1 0))
  ([input-array bufnum phase interp] (ibuf-wr:kr input-array bufnum phase interp 0))
  ([input-array bufnum phase interp feedback]
   (ibuf-wr-new :control input-array bufnum phase interp feedback)))
