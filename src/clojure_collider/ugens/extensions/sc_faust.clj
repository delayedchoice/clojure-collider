(ns clojure-collider.ugens.extensions.sc-faust
  "Port of cl-collider ugens/Extensions/sc_faust.lisp (custom Faust forms).
  Hand-ported; not generated by scripts/emit_ugens.clj."
  (:require [clojure-collider.synth.ugen :as ugen]
            [clojure-collider.ugens.line :as line]
            [clojure-collider.ugens.trig :as trig]))

;; ---- hand customs (preserved across regeneration) ----

(defonce ^:private faust-register-table (atom {}))

(defn- faust-base-hash [name]
  (let [h (hash name)]
    (long (* (mod h 1048576) (Integer/signum (long h))))))

(defn- faust-hash [name]
  (let [h (faust-base-hash name)]
    (doseq [n (remove #(= % name) (keys @faust-register-table))]
      (when (= h (faust-base-hash n))
        (throw (ex-info (str "Conflict hash key " name " and " n)
                        {:name name :other n}))))
    h))

(defn faust-all
  "Returns a list of Faust DSP modules and their parameters sent to the server."
  []
  (mapv (fn [[k v]] [:name k :params v]) @faust-register-table))

(defn faust:ar
  "Port of Extensions/sc_faust.lisp faust.ar (\"Faust\" multiout).
  The DSP must be registered under name (upstream faust-send);
  compiler/server delivery (faust-init/send/load/free) has no *s*/OSC
  counterpart in this port and is omitted."
  [num-output name & {:keys [inputs params] :or {inputs nil params nil}}]
  (let [spec (get @faust-register-table name)]
    (assert spec (str "Can't found faust module " name))
    (let [in-list (cond (nil? inputs) [] (sequential? inputs) (vec inputs) :else [inputs])
          param-list (cond (nil? params) [] (sequential? params) (vec params) :else [params])]
      (assert (even? (count param-list)) "params should be pair of key, value")
      (let [pnames (mapv #(str (:name %)) spec)
            resolved (vec (mapcat (fn [[key value]]
                                    (let [ks (if (keyword? key)
                                               (clojure.core/name key)
                                               (str key))
                                          idx (.indexOf pnames ks)
                                          entry (when (>= idx 0) (nth spec idx))]
                                      (assert entry
                                              (str "Can't found param " key
                                                   " in faust module " name))
                                      [idx (trig/clip:ar
                                            (if (= :audio (ugen/rate value))
                                              value
                                              (line/k2a:ar value))
                                            (:min entry) (:max entry))]))
                                  (partition 2 param-list)))
            ups (mapv (fn [sig]
                        (if (= :audio (ugen/rate sig)) sig (line/k2a:ar sig)))
                      in-list)
            all (into [(faust-hash name) (count ups) (/ (count resolved) 2)]
                      (concat ups resolved))]
        (apply ugen/multinew
               (fn [_cls & args]
                 (apply ugen/multiout-new "Faust" :audio :bipolar num-output args))
               'multiout-ugen
               all)))))
