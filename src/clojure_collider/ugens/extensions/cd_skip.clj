(ns clojure-collider.ugens.extensions.cd-skip
  "Port of cl-collider ugens/Extensions/CDSkip.lisp (custom defugen forms).
  Hand-ported; not generated by scripts/emit_ugens.clj."
  (:require [clojure-collider.synth.ugen :as ugen]
            [clojure-collider.ugens.line :as line]))

;; ---- hand customs (preserved across regeneration) ----

(defn cd-skip:ar
  "Port of Extensions/CDSkip.lisp (cd-skip \"CDSkip\"). Stereo in is a
  two-element sequential; trigger inputs are promoted to audio rate."
  [in & {:keys [max-delay auto-mode auto-speed skip-trigger reset-trigger pos freeze clean]
         :or {max-delay 2.0 auto-mode 0 auto-speed 1 skip-trigger 0 reset-trigger 0 pos 0 freeze 0 clean 0}}]
  (let [skip-trigger (if (= :audio (ugen/rate skip-trigger)) skip-trigger (line/t2a:ar skip-trigger))
        reset-trigger (if (= :audio (ugen/rate reset-trigger)) reset-trigger (line/t2a:ar reset-trigger))
        pos (if (= :audio (ugen/rate pos)) pos (line/k2a:ar pos))]
    (ugen/multinew (fn [_cls in0 in1 max-delay auto-mode auto-speed skip-trigger reset-trigger pos freeze clean]
                     (ugen/multiout-new "CDSkip" :audio :bipolar 2 in0 in1 max-delay auto-mode auto-speed skip-trigger reset-trigger pos freeze clean))
                   'multiout-ugen (nth in 0) (nth in 1) max-delay auto-mode auto-speed skip-trigger reset-trigger pos freeze clean)))
